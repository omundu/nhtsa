    def test_it_builds_url_as_expected
      expected_url = 'https://api.nhtsa.gov/CSSIStation?lat=0.0000&long=0.0000&miles=10'

      assert_equal expected_url, Nhtsa::ChildSafetySeatInspectionStationLocator::GetByGeoLocation.new("0.0000", "0.0000", 10).url
    end

    def test_url_returns_the_expected_string_with_cps_filter
      expected_url = 'https://api.nhtsa.gov/CSSIStation?lat=0.0000&long=0.0000&miles=10/cpsweek'

      assert_equal expected_url, Nhtsa::ChildSafetySeatInspectionStationLocator::GetByGeoLocation.new("0.0000", "0.0000", 10, {:cpsweek => true}).url
    end

    def test_url_returns_the_expected_string_with_spanish_filter
      expected_url = 'https://api.nhtsa.gov/CSSIStation?lat=0.0000&long=0.0000&miles=10/lang/spanish'

      assert_equal expected_url, Nhtsa::ChildSafetySeatInspectionStationLocator::GetByGeoLocation.new("0.0000", "0.0000", 10, {:spanish => true}).url
    end

    def test_url_returns_the_expected_string_with_cps_and_spanish_filter
      expected_url = 'https://api.nhtsa.gov/CSSIStation?lat=0.0000&long=0.0000&miles=10/cpsweek/lang/spanish'

